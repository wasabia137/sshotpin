  const SUPPORTED = ['ko', 'ja', 'zh', 'es', 'fr', 'de', 'pt', 'ru', 'en'];

  function resolve(locale) {
    const l = String(locale || '').toLowerCase();
    for (const s of SUPPORTED) if (l.startsWith(s)) return s;
    return 'en';
  }

  // 번역 함수: T('원문', {p: 값}) — ko거나 사전에 없으면 원문에 자리표만 채워 반환
  function translator(lang) {
    const d = STR[lang] || null;
    return (s, params) => {
      let out = (d && d[s]) || s;
      if (params) for (const k of Object.keys(params)) out = out.split(`{${k}}`).join(params[k]);
      return out;
    };
  }

  function applyPage(lang, page, doc) {
    const map = (UI[lang] || {})[page];
    if (!map) return;
    for (const [sel, spec] of Object.entries(map)) {
      const els = doc.querySelectorAll(sel);
      for (const el of els) {
        if (spec.text != null) el.textContent = spec.text;
        if (spec.html != null) el.innerHTML = spec.html;
        if (spec.title != null) el.title = spec.title;
        if (spec.ph != null) el.placeholder = spec.ph;
      }
    }
  }

  return { resolve, translator, applyPage, STR, UI };
